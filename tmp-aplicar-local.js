const fs = require('fs');
let src = fs.readFileSync('fuente.js','utf8');
const start = src.indexOf('function Locales(');
if (start < 0) throw new Error('No se encontró function Locales');
const next = src.indexOf('\nfunction ', start + 10);
const end = next < 0 ? src.length : next;
let bloque = src.slice(start, end);
const antes = bloque;
const reActivos = /const activos = locales\.filter\([^;]+\);/;
const reInactivos = /const inactivos = locales\.filter\([^;]+\);/;
if (!reActivos.test(bloque)) throw new Error('No se encontró definición de activos');
if (!reInactivos.test(bloque)) throw new Error('No se encontró definición de inactivos');
bloque = bloque.replace(reActivos, 'const activos = locales.filter((l2) => l2.activo !== false && !l2.fusionadoEn);');
bloque = bloque.replace(reInactivos, 'const inactivos = locales.filter((l2) => l2.activo === false && !l2.fusionadoEn);');
if (bloque === antes) throw new Error('No hubo cambios en Locales');
src = src.slice(0, start) + bloque + src.slice(end);
fs.writeFileSync('fuente.js', src);
fs.mkdirSync('tmp-inspeccion', { recursive: true });
fs.writeFileSync('tmp-inspeccion/locales-check.txt', bloque.includes('!l2.fusionadoEn') ? 'OK duplicados fusionados ocultos\n' : 'FAIL\n');
console.log('Duplicados técnicos fusionados ocultos en la UI de Locales');
