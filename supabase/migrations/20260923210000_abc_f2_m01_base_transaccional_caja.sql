create table public.abc_operaciones (
  operation_id text primary key,
  empresa_id text not null,
  local_id text not null,
  command_type text not null,
  request_hash text not null,
  status text not null default 'PROCESANDO',
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  terminal_id uuid,
  request jsonb not null default '{}'::jsonb,
  resultado jsonb,
  error jsonb,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint abc_operacion_id_formato
    check (operation_id ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,199}$'),
  constraint abc_operacion_command_type
    check (nullif(btrim(command_type),'') is not null),
  constraint abc_operacion_request_hash
    check (request_hash ~ '^[0-9a-f]{64}$'),
  constraint abc_operacion_status
    check (status in ('PROCESANDO','COMPLETADA','FALLIDA')),
  constraint abc_operacion_estado_consistente check (
    (status='PROCESANDO' and completed_at is null and resultado is null and error is null)
    or
    (status='COMPLETADA' and completed_at is not null and resultado is not null and error is null)
    or
    (status='FALLIDA' and completed_at is not null and error is not null)
  ),
  constraint abc_operacion_local_fk
    foreign key (empresa_id,local_id)
    references public.locales(empresa_id,id) on delete restrict,
  constraint abc_operacion_terminal_fk
    foreign key (empresa_id,local_id,terminal_id)
    references public.terminales_tpv(empresa_id,local_id,id) on delete restrict
);
create unique index abc_operacion_scope_id_uq
  on public.abc_operaciones(empresa_id,local_id,operation_id);
create index abc_operacion_scope_created_idx
  on public.abc_operaciones(empresa_id,local_id,created_at desc);

create trigger g1_operation_id_global
