create table public.caja_sesiones (
  id uuid primary key default gen_random_uuid(),
  empresa_id text not null,
  local_id text not null,
  caja_id uuid not null,
  estado text not null default 'PREPARANDO_APERTURA',
  version bigint not null default 1,
  abierta_at timestamptz,
  cerrada_at timestamptz,
  abierta_por uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint abc_sesion_estado
    check (estado in (
      'PREPARANDO_APERTURA','ABIERTA','EN_CIERRE',
      'CIERRE_PROVISIONAL','CERRADA_FINAL','APERTURA_CANCELADA'
    )),
  constraint abc_sesion_version check (version >= 1),
  constraint abc_sesion_tiempos check (
    (estado in ('CERRADA_FINAL','APERTURA_CANCELADA') and cerrada_at is not null)
    or
    (estado not in ('CERRADA_FINAL','APERTURA_CANCELADA') and cerrada_at is null)
  ),
  constraint abc_sesion_caja_fk
    foreign key (empresa_id,local_id,caja_id)
    references public.cajas_fisicas(empresa_id,local_id,id) on delete restrict
);
create unique index abc_sesion_scope_id_uq
  on public.caja_sesiones(empresa_id,local_id,id);
create unique index abc_sesion_activa_por_caja_uq
  on public.caja_sesiones(caja_id)
  where estado in ('PREPARANDO_APERTURA','ABIERTA','EN_CIERRE','CIERRE_PROVISIONAL');
create index abc_sesion_scope_estado_idx
  on public.caja_sesiones(empresa_id,local_id,estado,created_at desc);

