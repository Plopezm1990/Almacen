create table public.caja_cierres (
  id uuid primary key default gen_random_uuid(),
  empresa_id text not null,
  local_id text not null,
  session_id uuid not null,
  estado text not null default 'INICIADO',
  version bigint not null default 1,
  expected_snapshot jsonb not null default '{}'::jsonb,
  iniciado_por uuid not null references auth.users(id) on delete restrict,
  finalizado_por uuid references auth.users(id) on delete restrict,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint abc_cierre_estado check (estado in ('INICIADO','PROVISIONAL','FINAL','CANCELADO')),
  constraint abc_cierre_version check (version >= 1),
  constraint abc_cierre_tiempos check (
    (estado in ('FINAL','CANCELADO') and completed_at is not null)
    or
    (estado in ('INICIADO','PROVISIONAL') and completed_at is null)
  ),
  constraint abc_cierre_finalizador check (
    (estado in ('FINAL','CANCELADO') and finalizado_por is not null)
    or
    (estado in ('INICIADO','PROVISIONAL') and finalizado_por is null)
  ),
  constraint abc_cierre_sesion_fk
    foreign key (empresa_id,local_id,session_id)
    references public.caja_sesiones(empresa_id,local_id,id) on delete restrict
);
create unique index abc_cierre_scope_id_uq
  on public.caja_cierres(empresa_id,local_id,id);
create unique index abc_cierre_activo_por_sesion_uq
  on public.caja_cierres(session_id)
  where estado in ('INICIADO','PROVISIONAL');
create unique index abc_cierre_final_por_sesion_uq
  on public.caja_cierres(session_id)
  where estado='FINAL';

