CREATE TABLE public.perfiles (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  rol text NOT NULL DEFAULT 'Básico',
  empleado_id text NULL REFERENCES public.empleados(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  nombre text NULL,
  activo boolean NOT NULL DEFAULT true,
  CONSTRAINT perfiles_rol_check CHECK (
    rol = ANY (ARRAY['Propietario'::text,'Encargado'::text,'Básico'::text,'Camarero/a'::text,'Cajero/a'::text,'Churrero/a'::text])
  ),
  CONSTRAINT pm11_perfiles_empleado_no_vacio CHECK (
    empleado_id IS NULL OR NULLIF(btrim(empleado_id), '') IS NOT NULL
  )
);

CREATE TABLE public.membresias_usuario (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  empresa_id text NOT NULL,
  local_id text NULL,
  todos_locales boolean NOT NULL DEFAULT false,
  rol text NOT NULL,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.almacen_kv (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  empresa_id text NULL,
  local_id text NULL
);

CREATE TABLE public.stock_ubicacion (
  empresa_id text NOT NULL,
  local_id text NOT NULL,
  producto_id text NOT NULL,
  almacen numeric NOT NULL DEFAULT 0 CHECK (almacen >= 0),
  piso numeric NOT NULL DEFAULT 0 CHECK (piso >= 0),
  minimo numeric NOT NULL DEFAULT 0 CHECK (minimo >= 0),
  fraccionable boolean NOT NULL DEFAULT false,
  precision_cantidad smallint NOT NULL DEFAULT 0 CHECK (precision_cantidad BETWEEN 0 AND 6),
  updated_at timestamptz NOT NULL DEFAULT now(),
  local_operable boolean NOT NULL DEFAULT true,
  unidad text NOT NULL DEFAULT 'ud',
  PRIMARY KEY (empresa_id, local_id, producto_id)
);

CREATE TABLE public.stock_operaciones (
  operation_id text PRIMARY KEY,
  tipo text NOT NULL,
  empresa_id text NOT NULL,
  local_id text NOT NULL,
  producto_id text NOT NULL,
  payload jsonb NOT NULL,
  actor_user_id uuid NOT NULL,
  ref_operation_id text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT stock_operaciones_tipo_check CHECK (
    tipo = ANY (ARRAY['VENTA'::text,'REVERSO'::text,'TRASLADO_INTERNO'::text,'TRASLADO_ENTRE_LOCALES'::text,'DEVOLUCION_CLIENTE'::text,'DEVOLUCION_PROVEEDOR'::text])
    OR tipo = 'INVENTARIO_PM12'
  )
);

CREATE TABLE public.movimientos_stock (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id text NOT NULL REFERENCES public.stock_operaciones(operation_id) ON DELETE RESTRICT,
  tipo text NOT NULL,
  empresa_id text NOT NULL,
  local_id text NOT NULL,
  producto_id text NOT NULL,
  delta_almacen numeric NOT NULL,
  delta_piso numeric NOT NULL,
  delta_total numeric NOT NULL,
  cantidad numeric NOT NULL CHECK (cantidad > 0),
  movimiento_original_id bigint NULL REFERENCES public.movimientos_stock(id) ON DELETE RESTRICT,
  datos jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT movimientos_stock_tipo_check CHECK (
    tipo = ANY (ARRAY['VENTA'::text,'REVERSO'::text,'TRASLADO_INTERNO'::text,'TRASLADO_ENTRE_LOCALES'::text,'DEVOLUCION_CLIENTE'::text,'DEVOLUCION_PROVEEDOR'::text])
    OR tipo = 'INVENTARIO_PM12'
  ),
  CONSTRAINT pm07_delta_total_consistente CHECK (round(delta_total, 6) = round(delta_almacen + delta_piso, 6))
);

CREATE TABLE public.clientes_empresa (
  id text PRIMARY KEY,
  empresa_id text NOT NULL,
  datos jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT clientes_empresa_datos_empresa CHECK (
    (datos->>'empresaId') IS NULL OR (datos->>'empresaId') = empresa_id
  )
);

CREATE TABLE public.encargos_empresa (
  id text PRIMARY KEY,
  empresa_id text NOT NULL,
  local_id text NOT NULL,
  cliente_id text NULL,
  datos jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE private.g1_operation_ids_global (
  operation_id text PRIMARY KEY,
  ledger text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pagos_encargo (
  id text PRIMARY KEY,
  operation_id text NOT NULL UNIQUE,
  encargo_id text NOT NULL,
  empresa_id text NOT NULL,
  local_id text NOT NULL,
  concepto text NOT NULL CHECK (concepto = ANY (ARRAY['SEÑAL'::text,'RESTO_ENTREGA'::text,'OTRO'::text])),
  importe numeric NOT NULL CHECK (importe > 0),
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  estado text NOT NULL CHECK (estado = ANY (ARRAY['CONFIRMADO'::text,'REVERSO'::text])),
  revierte_pago_id text NULL REFERENCES public.pagos_encargo(id),
  medio_pago text NULL CHECK (medio_pago IS NULL OR medio_pago = ANY (ARRAY['Efectivo'::text,'Tarjeta'::text,'Transferencia'::text,'Otro'::text])),
  datos jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id uuid NOT NULL DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE supabase_migrations.schema_migrations (
  version text PRIMARY KEY,
  name text,
  created_by text
);

