-- PM27 / C24 — baseline estructural pre-C13 para certificacion aislada PostgreSQL 17.
--
-- Este fixture NO contiene datos de negocio. Reproduce únicamente el contrato de
-- esquema, firmas y privilegios que las migraciones C13->C23 necesitan para
-- compilar y validar sus pre/postcondiciones. Las formas relevantes se contrastaron
-- por lectura contra L&A Suite QA (PostgreSQL 17) antes de versionarlo.
--
-- El estado deliberadamente representa un destino limpio PRE-C13:
--   * no contiene marcadores funcionales C13-C23;
--   * conserva el trigger global operation_id previo a C22;
--   * incluye private.es_propietario_activo() en estado todavía no endurecido,
--     para que C13-P5 demuestre el hardening real;
--   * mantiene RPC legacy ejecutables para verificar que C13 las retira.

\set ON_ERROR_STOP on

DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
END
$roles$;

