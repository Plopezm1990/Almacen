async function limpiar() {
  await admin.query(`
    drop schema if exists private cascade;
    drop schema if exists auth cascade;
    drop table if exists public.empresas, public.locales, public.membresias_usuario cascade;
    create schema private;
    create schema auth;
    revoke all on schema private from public, authenticated, anon;
    grant usage on schema private to postgres;
  `);
}

async function montar() {
  await admin.query(`
    create table auth.users (id uuid primary key, email text, deleted_at timestamptz, encrypted_password text);
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;

    create table public.empresas (id text primary key, nombre text, activo boolean not null default true);
    create table public.locales (id text, empresa_id text, nombre text, activo boolean not null default true, primary key (empresa_id, id));
    create table public.membresias_usuario (
      id bigint generated by default as identity primary key,
      user_id uuid not null, empresa_id text not null, local_id text, todos_locales boolean not null default false,
      rol text not null, activo boolean not null default true
    );

    -- Stands-in mínimos: mismas firmas que producción (PM05/PM06), no el cuerpo entero.
    create function private.la_usuario_activo() returns boolean language sql stable as $$
      select auth.uid() is not null
    $$;
    create function private.la_rol() returns text language sql stable as $$
      select m.rol from public.membresias_usuario m
       where m.user_id = auth.uid() and m.activo = true
       order by m.id desc limit 1
    $$;
    create function private.la_tiene_local(p_empresa text, p_local text) returns boolean language sql stable as $$
      select exists (
        select 1 from public.membresias_usuario m
         where m.user_id = auth.uid() and m.empresa_id = p_empresa and m.activo = true
           and ((m.todos_locales = false and m.local_id = p_local) or (m.todos_locales = true and m.local_id is null))
      )
    $$;

    insert into auth.users(id) values ('${PROPIETARIO}'),('${ENCARGADO}'),('${CAJERO}'),('${CAMARERO}'),('${SIN_ROL}');
    insert into public.empresas(id, nombre) values ('E-A','Empresa A');
    insert into public.locales(empresa_id, id, nombre) values ('E-A','L-A1','Local A1');
    insert into public.membresias_usuario(user_id, empresa_id, local_id, todos_locales, rol) values
      ('${PROPIETARIO}','E-A',null,true,'Propietario'),
      ('${ENCARGADO}','E-A','L-A1',false,'Encargado'),
      ('${CAJERO}','E-A','L-A1',false,'Cajero/a'),
      ('${CAMARERO}','E-A','L-A1',false,'Camarero/a'),
      ('${SIN_ROL}','E-A','L-A1',false,'Churrero/a');
    update public.membresias_usuario set activo = true;
    update public.membresias_usuario set rol = 'Churrero/a' where user_id = '${SIN_ROL}';
    -- SIN_ROL sirve de "rol insuficiente" para las funciones que exigen Propietario/Encargado(/Cajero).
  `);
}

