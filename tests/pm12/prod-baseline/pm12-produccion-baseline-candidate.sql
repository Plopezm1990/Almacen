create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 1. Scope multiempresa/multilocal. Fail-closed: no se inventan membresías.
-- ---------------------------------------------------------------------------
create table public.membresias_usuario (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  empresa_id text not null,
  local_id text,
  todos_locales boolean not null default false,
  rol text not null,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pm12_prod_membresia_empresa check (nullif(btrim(empresa_id),'') is not null),
  constraint pm12_prod_membresia_local check (
    (todos_locales = true and local_id is null)
    or
    (todos_locales = false and nullif(btrim(local_id),'') is not null)
  )
);
create unique index pm12_prod_membresia_scope
  on public.membresias_usuario(user_id,empresa_id,coalesce(local_id,'__TODOS__'));
alter table public.membresias_usuario enable row level security;
revoke all on table public.membresias_usuario from public, anon, authenticated;

create or replace function private.la_usuario_activo()
returns boolean
language sql
stable security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
     and exists(
       select 1
         from public.membresias_usuario m
        where m.user_id=(select auth.uid())
          and m.activo=true
     )
     and not exists(
       select 1
         from public.perfiles p
        where p.user_id=(select auth.uid())
          and p.activo=false
     );
$$;

create or replace function private.la_rol()
returns text
language sql
stable security definer
set search_path = ''
as $$
  select coalesce(
    (
      select p.rol
        from public.perfiles p
       where p.user_id=(select auth.uid()) and p.activo=true
       limit 1
    ),
    (
      select m.rol
        from public.membresias_usuario m
       where m.user_id=(select auth.uid()) and m.activo=true
       order by m.empresa_id,m.local_id nulls first
       limit 1
    )
  );
$$;

create or replace function private.la_tiene_empresa(p_empresa text)
returns boolean
language sql
stable security definer
set search_path = ''
as $$
  select private.la_usuario_activo()
     and nullif(btrim(p_empresa),'') is not null
     and exists(
       select 1
         from public.membresias_usuario m
        where m.user_id=(select auth.uid())
          and m.empresa_id=p_empresa
          and m.activo=true
     );
$$;

create or replace function private.la_tiene_local(p_empresa text,p_local text)
returns boolean
language sql
stable security definer
set search_path = ''
as $$
  select private.la_usuario_activo()
     and nullif(btrim(p_empresa),'') is not null
     and nullif(btrim(p_local),'') is not null
     and upper(btrim(p_local)) <> 'TODOS'
     and exists(
       select 1
         from public.membresias_usuario m
        where m.user_id=(select auth.uid())
          and m.empresa_id=p_empresa
          and m.activo=true
          and (m.todos_locales=true or m.local_id=p_local)
     );
$$;

revoke all on function private.la_usuario_activo() from public, anon, authenticated;
revoke all on function private.la_rol() from public, anon, authenticated;
revoke all on function private.la_tiene_empresa(text) from public, anon, authenticated;
revoke all on function private.la_tiene_local(text,text) from public, anon, authenticated;
-- RLS SELECT policies execute this helper as authenticated. P08 grants schema usage;
-- the helper itself must therefore be executable, while the underlying table stays hidden.
grant execute on function private.la_tiene_local(text,text) to authenticated;

