create or replace function private.pm07_validar_cantidad(
  p_cantidad numeric,
  p_fraccionable boolean,
  p_precision smallint
) returns numeric
language plpgsql
immutable
set search_path = ''
as $$
declare v numeric;
begin
  if p_cantidad is null or p_cantidad::text in ('NaN','Infinity','-Infinity') then
    raise exception 'cantidad_invalida';
  end if;
  v := round(p_cantidad,greatest(0,least(6,coalesce(p_precision,0))));
  if v <= 0 then raise exception 'cantidad_invalida'; end if;
  if not coalesce(p_fraccionable,false) and v <> trunc(v) then raise exception 'unidad_indivisible'; end if;
  if p_cantidad <> v then raise exception 'precision_cantidad_excedida'; end if;
  return v;
end;
$$;

create or replace function private.pm07_puede_gestionar_stock()
returns boolean
language sql
stable security definer
set search_path = ''
as $$
  select private.la_usuario_activo()
     and coalesce(private.la_rol(),'') in ('Propietario','Encargado');
$$;

revoke all on function private.pm07_validar_cantidad(numeric,boolean,smallint) from public, anon, authenticated;
revoke all on function private.pm07_puede_gestionar_stock() from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3. Bloqueo/idempotencia mínima PM08–PM09/G1, sin crear ledgers financieros.
-- ---------------------------------------------------------------------------
create or replace function private.pm08_validar_operation_id(p_operation_id text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare v text := btrim(coalesce(p_operation_id,''));
begin
  if v !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{7,199}$' then raise exception 'operation_id_invalido'; end if;
  return v;
end;
$$;

create or replace function private.pm08_bloquear_operation_id(p_operation_id text)
returns void
language plpgsql
volatile
set search_path = ''
as $$
declare v text;
begin
  v := private.pm08_validar_operation_id(p_operation_id);
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('la-suite-pm08:'||v,0));
end;
$$;

create table private.g1_operation_ids_global (
  operation_id text primary key,
  ledger text not null,
  created_at timestamptz not null default now()
);
revoke all on table private.g1_operation_ids_global from public, anon, authenticated;

create or replace function private.g1_claim_operation_id()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare v_ledger text;
begin
  if new.operation_id is null or btrim(new.operation_id)='' then raise exception 'operation_id_requerido'; end if;
  insert into private.g1_operation_ids_global(operation_id,ledger)
  values(new.operation_id,tg_table_name)
  on conflict(operation_id) do nothing;
  select g.ledger into v_ledger
    from private.g1_operation_ids_global g
   where g.operation_id=new.operation_id;
  if v_ledger is distinct from tg_table_name then raise exception 'operation_id_conflict'; end if;
  return new;
end;
$$;

create trigger g1_operation_id_global
before insert on public.stock_operaciones
for each row execute function private.g1_claim_operation_id();

create or replace function private.pm09_bloquear_operation_id_stock(p_operation_id text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare v text; v_ledger text;
begin
  v := private.pm08_validar_operation_id(p_operation_id);
  perform private.pm08_bloquear_operation_id(v);
  select g.ledger into v_ledger
    from private.g1_operation_ids_global g
   where g.operation_id=v;
  if found and v_ledger <> 'stock_operaciones' then raise exception 'operation_id_conflict'; end if;
  return v;
end;
$$;

revoke all on function private.pm08_validar_operation_id(text) from public, anon, authenticated;
revoke all on function private.pm08_bloquear_operation_id(text) from public, anon, authenticated;
revoke all on function private.g1_claim_operation_id() from public, anon, authenticated;
revoke all on function private.pm09_bloquear_operation_id_stock(text) from public, anon, authenticated;

