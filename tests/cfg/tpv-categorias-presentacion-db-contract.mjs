// Contrato de base de datos para la presentación de categorías del TPV.
// Levanta un Postgres desechable en loopback, deja las dependencias mínimas
// (auth.uid, la_tiene_local, abc_tiene_capacidad, operaciones y eventos) y
// ejecuta la migración real tal y como está en el repositorio.
import pg from 'pg';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const url = new URL(process.env.TPV_CAT_TEST_DATABASE_URL || 'postgresql://postgres:postgres@127.0.0.1:5432/tpv_cat_test');
assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname), 'solo bases en loopback');
assert.equal(url.pathname, '/tpv_cat_test', 'solo la base desechable tpv_cat_test');

const MIGRACION = 'supabase/migrations/20261031120000_abc_tpv_categorias_presentacion.sql';
const admin = new pg.Client({ connectionString: url.href });
await admin.connect();
const abiertos = [];

async function actor(rol = 'Propietario', uid = '11111111-1111-1111-1111-111111111111', locales = 'L') {
  const c = new pg.Client({ connectionString: url.href });
  await c.connect();
  abiertos.push(c);
  await c.query("select set_config('tpvcat.actor',$1,false), set_config('tpvcat.rol',$2,false), set_config('tpvcat.locales',$3,false)", [uid, rol, locales]);
  await c.query('set role authenticated');
  return c;
}
const fallo = async (fn, codigo) => {
  try { await fn(); } catch (e) { assert.ok(String(e.message).includes(codigo), `esperaba ${codigo}, vino: ${e.message}`); return; }
  assert.fail(`esperaba que fallara con ${codigo}`);
};
const listar = async (c, e = 'E', l = 'L') => (await c.query('select public.abc_listar_categorias_tpv($1,$2) r', [e, l])).rows[0].r;
const guardar = async (c, cats, ver, opId = 'op-' + Math.random().toString(36).slice(2), e = 'E', l = 'L', dia = '2026-10-31') =>
  (await c.query('select public.abc_configurar_categorias_tpv($1,$2,$3,$4::jsonb,$5,$6,$7,$8) r',
    [opId, e, l, JSON.stringify(cats), ver, '22222222-2222-2222-2222-222222222222', '33333333-3333-3333-3333-333333333333', dia])).rows[0].r;

try {
  assert.equal((await admin.query('select current_database() db')).rows[0].db, 'tpv_cat_test');
  await admin.query(`
    drop schema if exists public cascade; drop schema if exists private cascade; drop schema if exists auth cascade;
    create schema public; create schema private; create schema auth;
    do $$begin
      if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
      if not exists(select 1 from pg_roles where rolname='anon') then create role anon; end if;
      if not exists(select 1 from pg_roles where rolname='service_role') then create role service_role; end if;
    end$$;
    grant usage on schema public, auth to authenticated;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('tpvcat.actor',true),'')::uuid$$;
    create table auth.users(id uuid primary key);
    insert into auth.users values ('11111111-1111-1111-1111-111111111111'),('44444444-4444-4444-4444-444444444444');
    create function private.la_tiene_local(e text, l text) returns boolean language sql stable as
      $$select e='E' and l = any(string_to_array(coalesce(current_setting('tpvcat.locales',true),''),','))$$;
    -- Misma plantilla que el servidor: ABC_SALA_CONFIGURAR es de Propietario y Encargado.
    create function private.abc_tiene_capacidad(e text, l text, cap text) returns boolean language sql stable as
      $$select case when cap='ABC_SALA_CONFIGURAR'
                    then coalesce(current_setting('tpvcat.rol',true),'') in ('Propietario','Encargado')
                    else false end$$;
    create table public.abc_operaciones(
      empresa_id text not null, local_id text not null, operation_id text not null,
      command_type text, request jsonb, resultado jsonb, terminal_id uuid,
      primary key (empresa_id, local_id, operation_id));
    create table public.abc_eventos(
      id bigint generated by default as identity primary key,
      empresa_id text not null, local_id text not null, operation_id text not null,
      aggregate_type text not null, aggregate_id text not null, event_type text not null,
      payload jsonb not null default '{}'::jsonb, actor_user_id uuid not null references auth.users(id),
      terminal_id uuid, occurred_at timestamptz not null, operating_day date not null,
      constraint abc_evento_operacion_fk foreign key (empresa_id,local_id,operation_id)
        references public.abc_operaciones(empresa_id,local_id,operation_id) on delete restrict);
    create function private.abc_operacion_iniciar(p_operation_id text,p_empresa_id text,p_local_id text,p_command_type text,p_request jsonb,p_terminal_id uuid)
    returns jsonb language plpgsql volatile security definer set search_path='' as $fn$
    declare v_fila public.abc_operaciones%rowtype;
    begin
      select * into v_fila from public.abc_operaciones
        where empresa_id=p_empresa_id and local_id=p_local_id and operation_id=p_operation_id for update;
      if found then return jsonb_build_object('replayed',true,'resultado',v_fila.resultado); end if;
      insert into public.abc_operaciones(empresa_id,local_id,operation_id,command_type,request,terminal_id)
        values(p_empresa_id,p_local_id,p_operation_id,p_command_type,p_request,p_terminal_id);
      return jsonb_build_object('replayed',false);
    end $fn$;
    create function private.abc_operacion_completar(p_operation_id text, p_resultado jsonb)
    returns void language plpgsql volatile security definer set search_path='' as $fn$
    begin update public.abc_operaciones set resultado=p_resultado where operation_id=p_operation_id; end $fn$;
    -- El local de QA corta el día a las 04:00; aquí basta con que devuelva un día.
    create function private.abc_resolver_operating_day_contexto(p_empresa_id text, p_local_id text, p_occurred_at timestamptz)
    returns jsonb language plpgsql stable security definer set search_path='' as $fn$
    begin
      if p_local_id <> 'L' then raise exception 'operating_day_local_no_disponible'; end if;
      return jsonb_build_object('operating_day', (p_occurred_at at time zone 'Europe/Madrid' - interval '4 hours')::date);
    end $fn$;
  `);

  await admin.query(fs.readFileSync(MIGRACION, 'utf8'));
  console.log('MIGRACION_APLICADA=1');

  const prop = await actor('Propietario');
  const cam = await actor('Camarero/a', '44444444-4444-4444-4444-444444444444');
  const ajeno = await actor('Propietario', '11111111-1111-1111-1111-111111111111', 'OTRO');

  // 1. Sin configurar: el TPV se queda con su orden por defecto.
  let r = await listar(prop);
  assert.equal(r.ok, true); assert.equal(Number(r.version), 0); assert.deepEqual(r.categorias, []);
  console.log('SIN_CONFIGURAR_DEVUELVE_VACIO=PASS');

  // 2. El Propietario guarda; la versión arranca en 1 y respeta el orden dado.
  r = await guardar(prop, [{ categoria: 'Bebidas', color: 'AZUL' }, { categoria: 'Tapas', color: 'naranja' }], 0);
  assert.equal(Number(r.version), 1);
  assert.deepEqual(r.categorias.map(c => c.categoria), ['Bebidas', 'Tapas']);
  assert.equal(r.categorias[1].color, 'NARANJA', 'el color se normaliza a mayúsculas');
  console.log('GUARDA_Y_NORMALIZA=PASS');

  // 3. Se lee lo guardado, en el mismo orden.
  r = await listar(prop);
  assert.equal(Number(r.version), 1);
  assert.deepEqual(r.categorias.map(c => c.categoria), ['Bebidas', 'Tapas']);
  console.log('LECTURA_CONSERVA_ORDEN=PASS');

  // 4. Versión obsoleta: falla cerrado, no pisa lo del otro terminal.
  await fallo(() => guardar(prop, [{ categoria: 'Tapas', color: 'ROJO' }], 0), 'tpv_categorias_version_conflict');
  r = await listar(prop);
  assert.deepEqual(r.categorias.map(c => c.categoria), ['Bebidas', 'Tapas'], 'el conflicto no debe cambiar nada');
  console.log('BLOQUEO_OPTIMISTA=PASS');

  // 5. Con la versión buena sí reordena.
  r = await guardar(prop, [{ categoria: 'Tapas', color: 'ROJO' }, { categoria: 'Bebidas', color: 'AZUL' }], 1);
  assert.equal(Number(r.version), 2);
  assert.deepEqual(r.categorias.map(c => c.categoria), ['Tapas', 'Bebidas']);
  console.log('REORDENA=PASS');

  // 6. Sin la capacidad no se puede escribir, aunque tenga el local.
  await fallo(() => guardar(cam, [{ categoria: 'Tapas', color: 'ROJO' }], 2), 'abc_tpv_categorias_no_autorizada');
  console.log('CAMARERO_NO_CONFIGURA=PASS');

  // 7. Quien no tiene el local no lee ni escribe.
  await fallo(() => listar(ajeno), 'abc_tpv_categorias_no_autorizada');
  await fallo(() => guardar(ajeno, [], 2), 'abc_tpv_categorias_no_autorizada');
  console.log('AISLAMIENTO_POR_LOCAL=PASS');

  // 8. Validación de la lista.
  await fallo(() => guardar(prop, [{ categoria: 'Tapas', color: 'FUCSIA' }], 2), 'tpv_categorias_color_invalido');
  await fallo(() => guardar(prop, [{ categoria: 'Tapas', color: 'ROJO' }, { categoria: 'Tapas', color: 'AZUL' }], 2), 'tpv_categorias_duplicada');
  await fallo(() => guardar(prop, [{ categoria: '   ', color: 'ROJO' }], 2), 'tpv_categorias_nombre_invalido');
  await fallo(() => guardar(prop, Array.from({ length: 61 }, (_, i) => ({ categoria: 'C' + i, color: 'AZUL' })), 2), 'tpv_categorias_demasiadas');
  await fallo(() => guardar(prop, { no: 'array' }, 2), 'tpv_categorias_formato_invalido');
  console.log('VALIDACION=PASS');

  // 9. Reintento con el mismo operation_id: devuelve lo mismo y no vuelve a subir la versión.
  const opId = 'op-reintento-1';
  const primera = await guardar(prop, [{ categoria: 'Postres', color: 'GRANATE' }], 2, opId);
  const segunda = await guardar(prop, [{ categoria: 'Postres', color: 'GRANATE' }], 2, opId);
  assert.equal(Number(primera.version), 3);
  assert.deepEqual(segunda, primera, 'el reintento devuelve el mismo resultado');
  assert.equal(Number((await listar(prop)).version), 3, 'el reintento no sube la versión');
  console.log('IDEMPOTENCIA=PASS');

  // 10. Sin día operativo lo resuelve el servidor: la pantalla de ajustes no
  // necesita tener una cuenta abierta para poder guardar.
  r = await guardar(prop, [{ categoria: 'Vinos', color: 'MORADO' }], 3, 'op-sin-dia', 'E', 'L', null);
  assert.equal(Number(r.version), 4);
  assert.ok(/^\d{4}-\d{2}-\d{2}$/.test(String(r.operating_day).slice(0, 10)), 'el servidor devuelve el día que usó');
  const diaEvento = (await admin.query("select operating_day from public.abc_eventos order by id desc limit 1")).rows[0].operating_day;
  assert.ok(diaEvento, 'el evento queda con día operativo');
  console.log('DIA_OPERATIVO_DEL_SERVIDOR=PASS');

  // 11. Queda rastro de quién lo cambió.
  const ev = await admin.query("select event_type, aggregate_type, actor_user_id, payload from public.abc_eventos order by id");
  assert.equal(ev.rows.length, 4, 'un evento por cambio aplicado, ninguno por los rechazados');
  assert.equal(ev.rows[0].event_type, 'TPV_CATEGORIAS_PRESENTACION_CONFIGURADA');
  assert.equal(ev.rows[0].aggregate_type, 'TPV_CATEGORIAS_PRESENTACION');
  assert.equal(ev.rows[0].actor_user_id, '11111111-1111-1111-1111-111111111111');
  console.log('AUDITORIA=PASS');

  // 12. La tabla no se toca directamente desde la sesión del usuario.
  await fallo(() => prop.query('select * from public.tpv_categorias_presentacion'), 'permission denied');
  console.log('TABLA_SOLO_POR_FUNCION=PASS');

  console.log('\nTPV_CATEGORIAS_PRESENTACION_DB=PASS');
} finally {
  for (const c of abiertos) await c.end().catch(() => {});
  await admin.end().catch(() => {});
}
