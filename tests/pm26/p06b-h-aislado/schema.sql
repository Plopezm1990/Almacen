-- Un Postgres generico (p.ej. el paquete "postgresql" de Ubuntu en un
-- runner de CI) no trae los roles "anon"/"authenticated" de Supabase
-- por defecto -- se crean aqui si faltan, de forma idempotente.
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated;
  end if;
end
$$;

create schema if not exists auth;
create table if not exists auth.users (id uuid primary key);

-- Simula auth.uid() leyendo una variable de sesion, para poder cambiar
-- de identidad dentro de la misma conexion de prueba. Null-safe, igual
-- que el auth.uid() real de Supabase cuando no hay JWT.
create or replace function auth.uid() returns uuid
language sql stable as $$
  select nullif(current_setting('app.current_uid', true), '')::uuid;
$$;

create schema if not exists private;

create table if not exists public.membresias_usuario (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  empresa_id text not null,
  local_id text,
  todos_locales boolean not null default false,
  rol text not null,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.membresias_usuario enable row level security;

create table if not exists public.empleados (
  id text primary key,
  empresa_id text not null,
  local_id text not null,
  estado text not null default 'activo'
);

create table if not exists public.perfiles (
  user_id uuid primary key,
  rol text not null default 'Básico',
  empleado_id text references public.empleados(id),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.perfiles enable row level security;

create table if not exists public.suscripciones_push (
  endpoint text primary key,
  p256dh text not null,
  auth text not null,
  dispositivo text,
  creado_en timestamptz not null default now(),
  user_id uuid,
