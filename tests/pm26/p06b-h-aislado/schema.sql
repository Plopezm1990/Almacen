  id text primary key,
  operation_id text not null unique,
  encargo_id text not null,
  empresa_id text not null,
  local_id text not null,
  revierte_pago_id text references public.pagos_encargo(id)
);

-- Copia literal de la definicion vigente en QA de este helper (no se
-- toca en esta migracion; se reproduce aqui solo porque
-- membresia_propia_select depende de el).
create or replace function private.la_usuario_activo() returns boolean
language sql stable security definer
set search_path to 'public', 'auth', 'private', 'pg_temp'
as $$
  select exists (
    select 1
      from public.perfiles p
     where p.user_id = auth.uid()
       and p.activo = true
       and (
         (
           p.empleado_id is null
           and exists (
             select 1
               from public.membresias_usuario m
              where m.user_id = p.user_id
                and m.activo = true
           )
         )
         or
         (
           p.empleado_id is not null
           and exists (
             select 1
               from public.empleados e
               join public.membresias_usuario m
                 on m.user_id = p.user_id
                and m.activo = true
                and m.empresa_id = e.empresa_id
                and (
                  m.todos_locales = true
                  or (m.todos_locales = false and m.local_id = e.local_id)
                )
              where e.id = p.empleado_id
                and e.estado = 'activo'
           )
         )
       )
  );
$$;

-- Politicas vigentes en QA, byte a byte (estado ANTES de la migracion).
drop policy if exists qa_perfil_propio_select on public.perfiles;
create policy qa_perfil_propio_select on public.perfiles
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists qa_perfil_propio_update on public.perfiles;
create policy qa_perfil_propio_update on public.perfiles
  for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists qa_push_propio on public.suscripciones_push;
create policy qa_push_propio on public.suscripciones_push
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists membresia_propia_select on public.membresias_usuario;
create policy membresia_propia_select on public.membresias_usuario
  for select to authenticated
  using (
    (user_id = auth.uid())
    and (activo = true)
    and private.la_usuario_activo()
  );

grant usage on schema public to authenticated, anon;
grant select, insert, update, delete on public.perfiles, public.suscripciones_push, public.membresias_usuario to authenticated;
grant select on public.empleados to authenticated;
